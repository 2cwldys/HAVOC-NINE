#!/usr/bin/env python3
"""Extract the TS weapon table (s_weapon_info) from each Write_<weapon> function
in ts_i386.so. Resolves PIC-relative string leas + immediate numeric fields and
emits a C initializer block for dlls/ts_weapons.cpp.

!! SPARTA TWO-STAGE WARNING (memory [[sparta-overrides-write-weapon]]): the four combat-feel
!! columns this tool reads from Write_ bodies — damage(+0x1c), spread(+0x28), viewkick(+0x30),
!! recoil(+0x34) — are the DEAD EARLIER STAGE. Sparta() (@0x6fa78 -> SetSpartaWeapon @0x6fa34,
!! == client FUN_10007a80) OVERWRITES them for all 32 firearms after every Write_. Emit them
!! only as the byte-faithful Write-stage literals; the LIVE values belong in Sparta() in
!! dlls/ts_weapon_info.cpp. Every OTHER column here IS the live truth.

Field offsets (recovered from Write_beretta + cross-checked vs ak47/m4/knife):
  numerics: 0x04 clip, 0x1c damage(float), 0xcc tsweapon id, 0x348 fire-type(byte)
  strings (rep movs dest -> meaning): 0x44 name, 0x86 hud sprite, 0xe8 v_model,
           0x132 p_model, 0x172 p_model_sil, 0x1b2 w_model, 0x1f2 fire,
           0x232 fire_sil
NOT byte-exact reconstruction — we only pull the fields CTSGun uses.
"""
import re, subprocess, struct, sys

BIN = "reference/ts_i386.so"

STR_DEST = {0x44: "name", 0x86: "sprite", 0xe8: "shell", 0x132: "vmodel",
            0x172: "pmodel", 0x1b2: "pmodel_sil", 0x1f2: "wmodel",
            0x232: "animext", 0x2c6: "fire", 0x306: "fire_sil"}

def sh(cmd):
    return subprocess.run(cmd, shell=True, capture_output=True, text=True).stdout

# rodata string table: addr -> text
strings = {}
for line in sh(f"rz-bin -z {BIN} 2>/dev/null").splitlines():
    m = re.match(r"\s*\d+\s+0x([0-9a-f]+)\s+0x[0-9a-f]+\s+\d+\s+\d+\s+\S+\s+\S+\s+(.*)$", line)
    if m:
        strings[int(m.group(1), 16)] = m.group(2)

# Write_<weapon> symbols
writes = {}
for line in sh(f"nm {BIN} 2>/dev/null").splitlines():
    m = re.match(r"([0-9a-f]+)\s+[Tt]\s+Write_([a-z0-9_]+)__FP13s_weapon_info$", line)
    if m:
        writes[m.group(2)] = int(m.group(1), 16)

# Authoritative table index per weapon, from compile_weapons_info @0x6fe28:
# each Write_<w>(&table[i]) where table base lea = 0x7d30 and entry size = 0x3dc.
name_to_index = {}
cw = sh("objdump -d --start-address=0x6fe28 --stop-address=0x70320 "
        f"{BIN} 2>/dev/null")
pending_off = None
for line in cw.splitlines():
    m = re.search(r"lea\s+0x([0-9a-f]+)\(%e[a-z]+\),%e[a-z]+", line)
    if m:
        pending_off = int(m.group(1), 16)
    m = re.search(r"<Write_([a-z0-9_]+)__", line)
    if m and pending_off is not None:
        name_to_index[m.group(1)] = (pending_off - 0x7d30) // 0x3dc
        pending_off = None

def f32(imm):
    return struct.unpack("<f", struct.pack("<I", imm & 0xffffffff))[0]

def extract(addr):
    end = addr + 0x250
    dis = sh(f"objdump -d --start-address=0x{addr:x} --stop-address=0x{end:x} {BIN} 2>/dev/null")
    ebx = None
    ebx_pop = None
    nums, strs = {}, {}
    pending_src = None
    for line in dis.splitlines():
        # PIC base: "<a>: 5b pop %ebx" then "<b>: 81 c3 X add $0xX,%ebx"
        # ebx = (address of the pop instruction) + X
        if re.search(r"\bpop\s+%ebx", line):
            ebx_pop = int(line.split(":")[0].strip(), 16)
        m = re.search(r"add\s+\$0x([0-9a-f]+),%ebx", line)
        if m and ebx is None and ebx_pop is not None:
            ebx = ebx_pop + int(m.group(1), 16)
        # numeric immediates: movl/movb $imm, 0xOFF(%reg)
        m = re.search(r"mov[lb]?\s+\$0x([0-9a-f]+),0x([0-9a-f]+)\(%e[a-z]+\)", line)
        if m:
            nums[int(m.group(2), 16)] = int(m.group(1), 16)
        # string source: lea -0xY(%ebx),%esi  (ebx-relative)
        m = re.search(r"lea\s+-0x([0-9a-f]+)\(%ebx\),%esi", line)
        if m and ebx is not None:
            pending_src = ebx - int(m.group(1), 16)
        # string dest: lea 0xDEST(%reg),%edi  -> pairs with pending_src on rep movs
        m = re.search(r"lea\s+0x([0-9a-f]+)\(%e[a-z]+\),%edi", line)
        if m and pending_src is not None:
            dest = int(m.group(1), 16)
            strs[STR_DEST.get(dest, dest)] = strings.get(pending_src, "?")
            pending_src = None
    return nums, strs

def cstr(s):
    return f'"{s}"' if s and s != "?" else "nullptr"

rows = []
for name, addr in sorted(writes.items()):
    idx = name_to_index.get(name)
    if idx is None:
        continue  # e.g. flag — not in compile_weapons_info
    nums, strs = extract(addr)
    rows.append((idx, name, strs, nums))

rows.sort()
print("// generated by scripts/extract_weapons.py — fill into compile_weapons_info()")
for idx, name, strs, nums in rows:
    clip = nums.get(0x4, 0)
    dmg = round(f32(nums.get(0x1c, 0)), 2)  # !! SPARTA-OWNED — Write-stage only (see header)
    ftype = nums.get(0x348, 0)
    rate = round(f32(nums.get(0x18, 0)), 4)   # fire-rate (0x18)
    spread = round(f32(nums.get(0x28, 0)), 4)  # !! SPARTA-OWNED (0x28) — Write-stage only
    recoil = round(f32(nums.get(0x34, 0)), 4)  # !! SPARTA-OWNED (0x34) — Write-stage only
    print(f'  Write(&g_weaponInfo[{idx}], {cstr(strs.get("name"))}, '
          f'{cstr(strs.get("vmodel"))}, {cstr(strs.get("pmodel"))}, '
          f'{cstr(strs.get("wmodel"))}, {cstr(strs.get("animext"))}, '
          f'{cstr(strs.get("fire"))}, {clip}, {dmg}f, {ftype}, '
          f'{rate}f, {spread}f, {recoil}f); // {name}')
