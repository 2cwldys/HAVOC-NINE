#!/usr/bin/env python3
"""
divergence.py — what our tree adds to / changes from the pristine base SDK (halflife-updated).

Our repo is a FORK of halflife-updated, so it mixes inherited stock SDK with our TS reconstruction.
This classifies every dlls/ + cl_dll/ .cpp/.h against the base checkout:
  - TS-NEW      : file absent from the base    -> pure reconstruction (clean)
  - POLLUTED    : stock file we MODIFIED        -> TS behaviour injected into stock SDK
  - INHERITED   : stock file, unchanged         -> not ours, ignored
For each POLLUTED file it extracts the TS-relevant lines we added (new functions/methods + TS hooks),
so we can see (and later relocate) the reconstruction that's currently buried in stock files.

Self-contained (stdlib + `diff` + git). The base defaults to the fork point itself: `upstream/64bit-demo`
(the same ref stock_methods.py reads), exported to a temporary directory. A path in argv[1] or
$HLU_BASE overrides it. The old default, the buildchain's halflife-updated checkout, is a working tree
on whatever branch it happens to be on (64bit-client, with local edits), so the report could change
with unrelated work there.

  python3 scripts/coverage/divergence.py            -> reference/coverage/SDK_DIVERGENCE.md
  python3 scripts/coverage/divergence.py <basepath>
"""
import os, re, sys, subprocess, tempfile
from collections import defaultdict

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
BASE_REF = "upstream/64bit-demo"
BASE = sys.argv[1] if len(sys.argv) > 1 else os.environ.get("HLU_BASE")
SUBDIRS = ["dlls", "cl_dll"]
OUT = os.path.join(ROOT, "reference", "coverage", "SDK_DIVERGENCE.md")

# An added line that introduces TS reconstruction (vs an incidental edit).
TS_HOOK = re.compile(r"\b(CTS\w+|CM61\w+|CVip\w+|CBulletManager|CInfoBreakable)\b"
                     r"|\bTS[A-Z]\w*\s*\(|\bgmsg\w+|\bTSW_\w+|\bg_ts\w+|\bm_TS\w+|\bm_fl?TS\w+"
                     r"|register.*ts_|FStrEq|\bts_\w+\.h")
FUNC_DEF = re.compile(r"^\+\s*[A-Za-z_][\w:\*&<> ]*\b([A-Za-z_]\w*::~?\w+|[A-Za-z_]\w+)\s*\([^;]*$")
KEYWORDS = {"if", "for", "while", "switch", "return", "else", "do", "sizeof", "case"}


def rel(p):
    return os.path.relpath(p, ROOT)


def classify():
    ts_new, polluted, inherited = [], [], []
    for sd in SUBDIRS:
        ours_dir = os.path.join(ROOT, sd)
        base_dir = os.path.join(BASE, sd)
        for fn in sorted(os.listdir(ours_dir)):
            if not fn.endswith((".cpp", ".h")):
                continue
            ours = os.path.join(ours_dir, fn)
            base = os.path.join(base_dir, fn)
            if not os.path.exists(base):
                ts_new.append(ours)
            elif subprocess.run(["diff", "-q", base, ours], capture_output=True).returncode != 0:
                polluted.append((ours, base))
            else:
                inherited.append(ours)
    return ts_new, polluted, inherited


def added_ts_lines(base, ours):
    """TS-relevant added lines in `ours` vs `base`: (added_count, removed_count, [new func/hook lines])."""
    out = subprocess.run(["diff", base, ours], capture_output=True, text=True).stdout
    added = [l[2:] for l in out.splitlines() if l.startswith("> ")]
    removed = [l[2:] for l in out.splitlines() if l.startswith("< ")]
    hooks = []
    for l in added:
        s = l.strip()
        if not s or s.startswith(("//", "*", "/*")):
            continue
        fd = FUNC_DEF.match("+" + l)
        if fd and fd.group(1).split("::")[-1] not in KEYWORDS and ("::" in s or TS_HOOK.search(s)):
            hooks.append(("fn", fd.group(1)))
        elif TS_HOOK.search(s):
            hooks.append(("hook", s))
    return len(added), len(removed), hooks


def main():
    global BASE
    if BASE:
        if not os.path.isdir(BASE):
            sys.exit(f"base SDK not found: {BASE}")
        label = BASE
        report(label)
        return
    sha = subprocess.run(["git", "-C", ROOT, "rev-parse", "--short", BASE_REF],
                         capture_output=True, text=True).stdout.strip()
    if not sha:
        sys.exit(f"{BASE_REF} not found (git fetch upstream), or pass a base path as argv[1]")
    with tempfile.TemporaryDirectory(prefix="hlu-base-") as tmp:
        tar = subprocess.run(["git", "-C", ROOT, "archive", BASE_REF] + SUBDIRS, capture_output=True, check=True)
        subprocess.run(["tar", "-x", "-C", tmp], input=tar.stdout, check=True)
        BASE = tmp
        report(f"{BASE_REF} @ {sha}")


def report(label):
    ts_new, polluted, inherited = classify()

    L = ["# Divergence from the base SDK (halflife-updated)", "",
         f"Base: `{label}`. Generated by `scripts/coverage/divergence.py`. Classifies our dlls/+cl_dll/ "
         "sources against the pristine fork base, isolating TS reconstruction from inherited/modified SDK.", "",
         f"**{len(ts_new)} TS-new files · {len(polluted)} polluted stock files · {len(inherited)} inherited "
         "(unchanged) stock files.**", "",
         "## Polluted stock files — TS behaviour injected into stock SDK (relocation candidates)", "",
         "| stock file | +added | −removed | TS functions added | TS hooks injected |", "|---|--:|--:|---|--:|"]
    for ours, base in polluted:
        a, r, hooks = added_ts_lines(base, ours)
        fns = [h[1] for h in hooks if h[0] == "fn"]
        nhook = sum(1 for h in hooks if h[0] == "hook")
        fns_s = ", ".join(f"`{x}`" for x in fns)   # full list — never truncated
        L.append(f"| `{rel(ours)}` | {a} | {r} | {fns_s or '—'} | {nhook} |")

    L += ["", "## TS-new files (clean reconstruction)", "",
          ", ".join(f"`{rel(p)}`" for p in ts_new) or "—"]

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write("\n".join(L) + "\n")
    print(f"wrote {OUT}: {len(ts_new)} TS-new, {len(polluted)} polluted, {len(inherited)} inherited")


if __name__ == "__main__":
    main()
