#!/usr/bin/env python3
"""
commands.py — map each console command to its HANDLER function (where one exists) or its inline dispatcher.

The SDK has two command shapes, and (as the registration is centralized) they recover differently:
  - `pfnAddCommand("name", handler)` (client, in HUD_Init-ish): the handler is an explicit function —
    at the call site the name string AND the handler fn are both loaded @GOTOFF back-to-back, so we pair
    them (name string ref -> next .text fn ref).
  - server player commands: dispatched INLINE in `ClientCommand()` via `FStrEq(pcmd, "name")` if-chains —
    there is NO separate handler function, so we report the dispatcher (the function the string lives in)
    and mark it inline.
Command NAME list comes from coverage.py (authoritative); we locate each name's @GOTOFF ref to find its
home function + adjacent handler. ebx = _GLOBAL_OFFSET_TABLE_ (0x165e10); string/fn vaddr = GOT + disp.

Outputs:
  reference/coverage/COMMANDS.md     — command -> handler/dispatcher
  reference/coverage/commands.tsv    — name<TAB>kind<TAB>home_function<TAB>handler

  python3 scripts/coverage/commands.py
"""
import os, re, subprocess, sys
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import coverage as C

ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
SO   = os.path.join(ROOT, "reference", "ts_i386.so")
OUT_MD  = os.path.join(ROOT, "reference", "coverage", "COMMANDS.md")
OUT_TSV = os.path.join(ROOT, "reference", "coverage", "commands.tsv")
GOT = 0x165e10
DATA = open(SO, "rb").read()


def rodata():
    out = subprocess.check_output(["readelf", "-SW", SO], text=True)
    for ln in out.splitlines():
        m = re.search(r"\.rodata\s+\w+\s+([0-9a-f]+)\s+[0-9a-f]+\s+([0-9a-f]+)", ln)
        if m:
            a = int(m.group(1), 16)
            return a, a + int(m.group(2), 16)
    return 0xf6600, 0xf6600 + 0xa952


RO0, RO1 = rodata()


def func_table():
    funcs = {}
    for ln in subprocess.run(f"nm '{SO}'", shell=True, capture_output=True, text=True).stdout.splitlines():
        p = ln.split()
        if len(p) == 3 and p[1] in "TtWw":
            try:
                funcs[int(p[0], 16)] = p[2]
            except ValueError:
                pass
    return funcs


def cstr(va):
    e = DATA.index(b"\0", va)
    return DATA[va:e].decode("latin1", "replace")


def gotoff_seq():
    """{home_function: [(kind, value)]} ordered @GOTOFF refs — kind 'str'|'fn'|None."""
    funcs = func_table()
    dis = subprocess.run(["objdump", "-d", "--no-show-raw-insn", SO], capture_output=True, text=True).stdout
    seq = defaultdict(list)
    cur = None
    for ln in dis.splitlines():
        h = re.match(r"^[0-9a-f]+ <([^>]+)>:", ln)
        if h:
            cur = h.group(1)
            continue
        if cur is None:
            continue
        for m in re.finditer(r"(-?0x[0-9a-f]+)\(%ebx\)", ln):
            off = int(m.group(1), 16)
            if off > 0x7fffffff:
                off -= 0x100000000
            va = GOT + off
            if RO0 <= va < RO1:
                seq[cur].append(("str", cstr(va)))
            elif va in funcs:
                seq[cur].append(("fn", funcs[va]))
    return seq


def main():
    orig = C.extract_original()
    cmds = set(orig.get("server_commands", [])) | set(orig.get("client_commands", []))
    cl_cmds = set(orig.get("client_commands", []))
    seq = gotoff_seq()

    rows = {}   # name -> (kind, home, handler)
    for home, refs in seq.items():
        for i, (k, v) in enumerate(refs):
            if k == "str" and v in cmds and v not in rows:
                handler, kind = None, "inline"
                # client AddCommand: the handler fn is the next ref
                if i + 1 < len(refs) and refs[i + 1][0] == "fn":
                    handler, kind = refs[i + 1][1], "registered"
                rows[v] = (kind, home, handler)

    L = ["# Console commands -> handler / dispatcher", "",
         "Generated by `scripts/coverage/commands.py`. `registered` = `pfnAddCommand(\"name\", handler)` "
         "with an explicit handler fn; `inline` = dispatched inside the home function via `FStrEq` "
         "(no separate handler — the SDK pattern). Names from coverage.py.", "",
         f"**{len(rows)}/{len(cmds)} commands located.**", "",
         "| command | kind | home function | handler |", "|---|---|---|---|"]
    tsv = ["name\tkind\thome\thandler"]
    for name in sorted(rows):
        kind, home, handler = rows[name]
        L.append(f"| `{name}` | {kind} | `{home}` | {('`'+handler+'`') if handler else '—'} |")
        tsv.append(f"{name}\t{kind}\t{home}\t{handler or ''}")
    miss = sorted(cmds - set(rows))
    if miss:
        L += ["", f"_Not located via @GOTOFF ({len(miss)}): {', '.join(miss)}_"]
    open(OUT_MD, "w").write("\n".join(L) + "\n")
    open(OUT_TSV, "w").write("\n".join(tsv) + "\n")
    print(f"wrote {OUT_MD} + {OUT_TSV}: {len(rows)}/{len(cmds)} commands "
          f"({sum(1 for r in rows.values() if r[0]=='registered')} registered, "
          f"{sum(1 for r in rows.values() if r[0]=='inline')} inline)")


if __name__ == "__main__":
    main()
