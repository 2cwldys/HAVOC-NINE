#!/usr/bin/env python3
"""
signatures.py — best typed signature per function: RETURN type + params + const/virtual.

Two sources, merged (MSVC preferred — it carries the return type the gnu-v2 mangling lacks):
  - MSVC (reference/signatures-mp.txt server + signatures-client.txt client): full
    `public: virtual void __thiscall CFoo::Bar(class CBaseEntity *) const`
  - gcc2 (reference/signatures-gcc2.txt): `CFoo::Bar(params)` — params only, no return.
So a function gets its real return type where MSVC exported it (159 server + ~1013 client), else
params-only from gcc2 with return marked `?`. This is what makes each reconstructed prototype faithful.

Outputs:
  reference/coverage/SIGNATURES.md    — per class, typed methods
  reference/coverage/signatures.tsv   — class<TAB>method<TAB>return<TAB>params<TAB>qual<TAB>virtual<TAB>source

  python3 scripts/coverage/signatures.py            # all
  python3 scripts/coverage/signatures.py <Class>     # one class to stdout
"""
import os, re, sys
from collections import defaultdict

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
REF  = os.path.join(ROOT, "reference")
MSVC = [os.path.join(REF, "signatures-mp.txt"), os.path.join(REF, "signatures-client.txt")]
GCC2 = os.path.join(REF, "signatures-gcc2.txt")
OUT_MD  = os.path.join(ROOT, "reference", "coverage", "SIGNATURES.md")
OUT_TSV = os.path.join(ROOT, "reference", "coverage", "signatures.tsv")

MSVC_RE = re.compile(
    r"^(?:(?:public|protected|private): )?((?:static |virtual )*)(.+?) "
    r"(?:__thiscall|__cdecl|__stdcall) ([A-Za-z_]\w*)::(~?\w+)\((.*)\)\s*(const)?\s*$")
GCC2_RE = re.compile(r"^([A-Za-z_]\w*)::(~?\w+)\((.*)\)\s*$")


def norm(params):
    p = params.strip()
    return "" if p in ("void", "") else re.sub(r"\bclass\s+|\bstruct\s+", "", p)


def load():
    # key (class, method) -> dict; keep first MSVC (typed); else gcc2
    sig = {}
    for path in MSVC:
        if not os.path.exists(path):
            continue
        for ln in open(path, errors="replace"):
            m = MSVC_RE.match(ln.strip())
            if not m:
                continue
            mods, ret, cls, meth, params, const = m.groups()
            key = (cls, meth)
            if key not in sig or sig[key]["source"] != "msvc":
                sig[key] = {"return": ret.strip(), "params": norm(params),
                            "qual": "const" if const else "", "virtual": "virtual" in mods,
                            "source": "msvc"}
    if os.path.exists(GCC2):
        for ln in open(GCC2, errors="replace"):
            m = GCC2_RE.match(ln.strip())
            if not m:
                continue
            cls, meth, params = m.groups()
            key = (cls, meth)
            if key not in sig:
                sig[key] = {"return": "?", "params": norm(params), "qual": "", "virtual": False,
                            "source": "gcc2"}
    return sig


def render(cls, meth, s):
    v = "virtual " if s["virtual"] else ""
    q = f" {s['qual']}" if s["qual"] else ""
    return f"{v}{s['return']} {meth}({s['params']}){q}"


def main():
    sig = load()
    by_cls = defaultdict(dict)
    for (c, m), s in sig.items():
        by_cls[c][m] = s

    if len(sys.argv) > 1:
        c = sys.argv[1]
        print(f"# {c}")
        for m in sorted(by_cls.get(c, {})):
            print(f"  {render(c, m, by_cls[c][m])}    [{by_cls[c][m]['source']}]")
        return

    L = ["# Recovered typed signatures (MSVC return types + gcc2 params, merged)", "",
         "Generated by `scripts/coverage/signatures.py`. `?` return = no MSVC export (gnu-v2 mangling "
         "omits return types); params still exact from the mangling. Use these prototypes when writing "
         "each reconstructed method.", "",
         f"**{len(sig)} signatures · {sum(1 for s in sig.values() if s['source']=='msvc')} fully typed (MSVC).**", ""]
    tsv = ["Class\tmethod\treturn\tparams\tqual\tvirtual\tsource"]
    for c in sorted(by_cls):
        L += [f"## {c}", ""]
        for m in sorted(by_cls[c]):
            s = by_cls[c][m]
            L.append(f"- `{render(c, m, s)}`  _({s['source']})_")
            tsv.append(f"{c}\t{m}\t{s['return']}\t{s['params']}\t{s['qual']}\t{int(s['virtual'])}\t{s['source']}")
        L.append("")
    open(OUT_MD, "w").write("\n".join(L) + "\n")
    open(OUT_TSV, "w").write("\n".join(tsv) + "\n")
    print(f"wrote {OUT_MD} + {OUT_TSV}: {len(sig)} signatures "
          f"({sum(1 for s in sig.values() if s['source']=='msvc')} MSVC-typed)")


if __name__ == "__main__":
    main()
