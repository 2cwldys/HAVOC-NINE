#!/usr/bin/env python3
"""
precache.py — recover the ASSET LIST (models/sounds/sprites) each entity precaches.

Not visible from class/function/var inspection: every entity's `Precache()` calls
PRECACHE_MODEL/SOUND/... with string-literal paths. In the PIC .so those literals are referenced as
`lea disp(%ebx),reg` where ebx = _GLOBAL_OFFSET_TABLE_ (0x165e10), so the string vaddr = GOT + disp
(@GOTOFF). We disassemble each `Precache__<Class>` once and pull every .rodata string it references,
filtered to asset-like paths. These are the exact assets the original ships per entity — high-fidelity
data for the reconstruction (and for naming in Ghidra).

Outputs:
  reference/coverage/PRECACHE.md     — per class, assets by kind
  reference/coverage/precache.tsv    — class<TAB>kind<TAB>asset

  python3 scripts/coverage/precache.py            # all
  python3 scripts/coverage/precache.py <Class>     # one class
"""
import os, re, subprocess, sys
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import coverage as C   # cvar/command name lists (to tag those string refs)

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SO   = os.path.join(ROOT, "reference", "ts_i386.so")
OUT_MD  = os.path.join(ROOT, "reference", "coverage", "PRECACHE.md")
OUT_TSV = os.path.join(ROOT, "reference", "coverage", "precache.tsv")

GOT = 0x165e10
DATA = open(SO, "rb").read()
EXT = {".mdl": "model", ".wav": "sound", ".spr": "sprite", ".bsp": "map",
       ".tga": "sprite", ".txt": "file", ".sc": "event"}


def rodata_range():
    out = subprocess.check_output(["readelf", "-SW", SO], text=True)
    for ln in out.splitlines():
        m = re.search(r"\.rodata\s+\w+\s+([0-9a-f]+)\s+[0-9a-f]+\s+([0-9a-f]+)", ln)
        if m:
            a = int(m.group(1), 16)
            return a, a + int(m.group(2), 16)
    return 0xf6600, 0xf6600 + 0xa952


RO0, RO1 = rodata_range()


def cstr(va):
    e = DATA.index(b"\0", va)
    return DATA[va:e].decode("latin1", "replace")


def asset_kind(s):
    s2 = s.lower()
    for ext, kind in EXT.items():
        if s2.endswith(ext):
            return kind
    if "/" in s and " " not in s and len(s) > 4:
        return "path"
    return None


def name_sets():
    """({cvar names}, {command names}) from coverage — to tag those string refs per function."""
    try:
        o = C.extract_original()
        cv = set(o.get("server_cvars", {})) | set(o.get("client_cvars", {}))
        cm = set(o.get("server_commands", [])) | set(o.get("client_commands", []))
        return cv, cm
    except Exception:
        return set(), set()


def precache_strings():
    """{function_symbol: [(kind, value)]} — per FUNCTION (method granularity), one objdump pass.
    Captures the model/sound/sprite/event ASSETS plus cvar/command name refs each function uses, so the
    JSON maps file -> class -> method -> {asset,cvar,command}. (Precache/EMIT_SOUND/SET_MODEL/CVAR sites.)"""
    cvars, cmds = name_sets()
    dis = subprocess.run(["objdump", "-d", "--no-show-raw-insn", SO], capture_output=True, text=True).stdout
    out = defaultdict(list)
    cur = None
    for ln in dis.splitlines():
        h = re.match(r"^[0-9a-f]+ <([^>]+)>:", ln)
        if h:
            cur = h.group(1)            # the full function symbol
            continue
        if cur is None or cur.endswith("@plt"):
            continue
        for m in re.finditer(r"(-?0x[0-9a-f]+)\(%ebx\)", ln):
            off = int(m.group(1), 16)
            if off > 0x7fffffff:
                off -= 0x100000000
            va = GOT + off
            if RO0 <= va < RO1:
                s = cstr(va)
                # reject reads that start in the FP constant pool (a @GOTOFF to a float lands mid-.rodata
                # and cstr swallows binary bytes + the next string) — values are clean printable ASCII.
                if not (s.isascii() and s.isprintable()):
                    continue
                kind = asset_kind(s) or ("cvar" if s in cvars else "command" if s in cmds else None)
                if kind and (kind, s) not in out[cur]:
                    out[cur].append((kind, s))
    return {f: v for f, v in out.items() if v}


def main():
    pc = precache_strings()
    if len(sys.argv) > 1:
        q = sys.argv[1]
        for fn in sorted(pc):
            if q in fn:
                print(f"# {fn}")
                for kind, asset in pc[fn]:
                    print(f"  {kind:7} {asset}")
        return

    total = sum(len(v) for v in pc.values())
    L = ["# Recovered asset references, per FUNCTION (method granularity)", "",
         "Generated by `scripts/coverage/precache.py` — every model/sound/sprite/event path each "
         "FUNCTION references (@GOTOFF string refs in ts_i386.so): precached assets, played sounds, set "
         "models. Keyed by the function symbol so export maps file -> class -> method -> asset.", "",
         f"**{len(pc)} functions · {total} asset refs.**", ""]
    tsv = ["function\tkind\tasset"]
    for f in sorted(pc):
        L += [f"## {f}", ""]
        for kind, asset in pc[f]:
            L.append(f"- `{kind}` {asset}")
            tsv.append(f"{f}\t{kind}\t{asset}")
        L.append("")
    open(OUT_MD, "w").write("\n".join(L) + "\n")
    open(OUT_TSV, "w").write("\n".join(tsv) + "\n")
    print(f"wrote {OUT_MD} + {OUT_TSV}: {len(pc)} functions, {total} asset refs")


if __name__ == "__main__":
    main()
