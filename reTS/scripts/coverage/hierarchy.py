#!/usr/bin/env python3
"""
hierarchy.py — recover each class's BASE class from the original's typeinfo functions.

gcc2 builds RTTI at runtime: `__tf<Class>()` first calls `__tf<Base>()` for each direct base, then
`__rtti_si`/`__rtti_class` to register itself. So the `__tf` calls inside `__tf<Class>` ARE the declared
bases, recorded by the compiler (no inference). The earlier vtable slot-ownership heuristic got most
classes wrong (e.g. CTSKnife -> CTSPhysicObject; the binary says CTSGrenade) because an intermediate base
that overrides nothing owns no slots. Classes with more than one base are listed as multiple inheritance.

Needed for the refactor: writing `class CTSKnife : public CTSGrenade` faithfully instead of guessing.

Outputs:
  reference/coverage/HIERARCHY.md     — class -> base, and the rooted trees
  reference/coverage/hierarchy.tsv    — class<TAB>base

  python3 scripts/coverage/hierarchy.py            # all
  python3 scripts/coverage/hierarchy.py <Class>     # one class's ancestry chain
"""
import os, re, subprocess, sys
from collections import defaultdict

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SO   = os.path.join(ROOT, "reference", "ts_i386.so")
VT   = os.path.join(ROOT, "reference", "coverage", "VTABLES.md")
OUT_MD  = os.path.join(ROOT, "reference", "coverage", "HIERARCHY.md")
OUT_TSV = os.path.join(ROOT, "reference", "coverage", "hierarchy.tsv")


def load_vtables():
    """{class: [owner_class_per_slot]} from VTABLES.md (slot order = file order; None for unparsed)."""
    vt = defaultdict(list)
    cur = None
    for ln in open(VT, errors="replace"):
        h = re.match(r"^##\s+(\S+)", ln)
        if h:
            cur = h.group(1)
            continue
        if cur:
            m = re.search(r"→\s*([A-Za-z_]\w*)::(~?\w+)\s*\(", ln)
            if m:
                vt[cur].append(m.group(1))      # the OWNER class of this slot
            elif "→" in ln:
                vt[cur].append(None)
    return vt


def gcc2_name(lenname):
    """'11CBaseEntity' -> 'CBaseEntity' (None if the length prefix doesn't fit)."""
    m = re.match(r"(\d+)(\w+)$", lenname)
    if not m or len(m.group(2)) != int(m.group(1)):
        return None
    return m.group(2)


def typeinfo_bases():
    """{class: [direct bases in declaration order]} from the __tf<base> calls inside each __tf<class>."""
    dis = subprocess.run(["objdump", "-d", "--no-show-raw-insn", SO],
                         capture_output=True, text=True, errors="replace").stdout
    bases, cur = defaultdict(list), None
    for ln in dis.splitlines():
        h = re.match(r"^[0-9a-f]+ <__tf(\w+)>:$", ln)
        if h:
            cur = gcc2_name(h.group(1))
            continue
        if ln and not ln.startswith(" "):
            cur = None
            continue
        if cur:
            m = re.search(r"call\s+[0-9a-f]+ <__tf(\w+?)(?:@plt)?>", ln)
            b = gcc2_name(m.group(1)) if m else None
            if b and b != cur and b not in bases[cur]:
                bases[cur].append(b)
    return bases


def base_of(vt):
    """{class: primary base}. vt is kept for the class list; the bases come from the typeinfo code."""
    tb = typeinfo_bases()
    return {c: bs[0] for c, bs in tb.items() if bs}


def chain(c, base):
    out = [c]
    seen = {c}
    while c in base and base[c] not in seen:
        c = base[c]; out.append(c); seen.add(c)
    return out


def main():
    vt = load_vtables()
    base = base_of(vt)

    if len(sys.argv) > 1:
        c = sys.argv[1]
        print(" : ".join(f"public {x}" if i else x for i, x in enumerate(chain(c, base))))
        return

    children = defaultdict(list)
    for c, b in base.items():
        children[b].append(c)
    roots = sorted(set(vt) - set(base))

    multi = {c: bs for c, bs in typeinfo_bases().items() if len(bs) > 1}
    L = ["# Recovered class hierarchy (base classes from the original's typeinfo functions)", "",
         "Generated by `scripts/coverage/hierarchy.py`: each `__tf<Class>()` calls `__tf<Base>()` for its "
         "direct bases, so these are the declared bases, not an inference. `class X : public BASE` for the "
         "refactor.", "",
         f"**{len(vt)} classes · {len(base)} with a recovered base · {len(roots)} roots · "
         f"{len(multi)} with multiple inheritance.**", ""]
    if multi:
        L += ["## multiple inheritance (base listed below is the first)", ""]
        L += [f"- `{c}` : " + ", ".join(f"`{b}`" for b in bs) for c, bs in sorted(multi.items())]
        L += [""]
    L += ["## class → base", "", "| class | base |", "|---|---|"]
    tsv = ["Class\tbase"]
    for c in sorted(base):
        L.append(f"| `{c}` | `{base[c]}` |")
        tsv.append(f"{c}\t{base[c]}")

    def tree(node, depth, acc):
        acc.append("  " * depth + f"- {node}")
        for ch in sorted(children.get(node, [])):
            tree(ch, depth + 1, acc)

    L += ["", "## inheritance trees (TS-relevant roots)", ""]
    acc = []
    for r in roots:
        if any(x.startswith(("CTS", "CM61", "CVip", "CBulletManager")) for x in chain_down(r, children)):
            tree(r, 0, acc)
    L += acc

    open(OUT_MD, "w").write("\n".join(L) + "\n")
    open(OUT_TSV, "w").write("\n".join(tsv) + "\n")
    print(f"wrote {OUT_MD} + {OUT_TSV}: {len(base)} class→base relations")


def chain_down(node, children):
    out = [node]
    for ch in children.get(node, []):
        out += chain_down(ch, children)
    return out


if __name__ == "__main__":
    main()
