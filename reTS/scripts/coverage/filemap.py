#!/usr/bin/env python3
"""
filemap.py — recover the ORIGINAL source filename of every function in ts_i386.so.

GCC 2.x emits, per translation unit, an `STT_FILE` symbol naming the .cpp followed by a
`gcc2_compiled.` marker at that TU's .text start address. Sorted by address, the markers
partition .text into [start, next_start) ranges — one per source file. Every FUNC symbol is
then assigned to the file whose range contains its address. This is authoritative: the range
contents corroborate the filename (e.g. CTSKnife's methods land in TS_grenades.cpp alongside
CTSGrenade/CTSShrapnel/CM61Grenade — the original groups all throwables in one TU; TS_knife.cpp
holds only Write_knife, the weapon-table entry).

Output: reference/coverage/FILE_MAP.md — file -> classes/funcs, and a class -> file index.
The coverage tooling (reconstruction.py) matches methods by NAME; this map lets it also pin the
ORIGINAL FILE each class belongs to, so our source layout + names can be diffed against the
reference. Pure readelf/nm — no Ghidra.

Usage: scripts/coverage/filemap.py            # writes the report
       scripts/coverage/filemap.py <Class>    # print one class's file + methods
"""
import os, re, sys, subprocess
from collections import defaultdict

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SO   = os.path.join(ROOT, "reference", "ts_i386.so")
OUT  = os.path.join(ROOT, "reference", "coverage", "FILE_MAP.md")


def parse_symbols():
    out = subprocess.check_output(["readelf", "-sW", SO], text=True)
    rows = []
    for line in out.splitlines():
        p = line.split()
        if len(p) < 8 or not p[0].endswith(":"):
            continue
        try:
            val = int(p[1], 16)
        except ValueError:
            continue
        rows.append((p[3], val, p[7]))  # type, value, name
    return rows


def file_ranges(rows):
    """[(start, end, filename)] from FILE -> following gcc2_compiled. marker, sorted by addr."""
    starts, cur = [], None
    for typ, val, name in rows:
        if typ == "FILE":
            cur = name
        elif name == "gcc2_compiled." and cur is not None:
            starts.append((val, cur))
            cur = None
    starts = sorted(set(starts))
    ranges = []
    for i, (a, f) in enumerate(starts):
        end = starts[i + 1][0] if i + 1 < len(starts) else 0xFFFFFFFF
        ranges.append((a, end, f))
    return ranges


def file_of(addr, ranges):
    for a, e, f in ranges:
        if a <= addr < e:
            return f
    return "?"


def classname(mangled):
    """Best-effort gcc-v2 class name from a mangled symbol (Method__<len><Class>...)."""
    m = re.match(r"^[A-Za-z0-9_]+__(\d+)([A-Za-z0-9_]+)", mangled)
    if m:
        n = int(m.group(1))
        return m.group(2)[:n]
    if mangled.startswith("__"):  # ctor/dtor/operators
        m = re.match(r"^__\w+__?(\d+)([A-Za-z0-9_]+)", mangled)
        if m:
            return m.group(2)[: int(m.group(1))]
    return "(free)"


def build():
    rows = parse_symbols()
    ranges = file_ranges(rows)
    per_file = defaultdict(list)   # file -> [(addr, sym)]
    seen = set()
    for typ, val, name in rows:
        if typ == "FUNC" and val and name not in seen and name != "gcc2_compiled.":
            seen.add(name)
            per_file[file_of(val, ranges)].append((val, name))
    return per_file


def main():
    per_file = build()
    # class -> files (a class should live in exactly one TU; flag if not)
    cls_files = defaultdict(set)
    for f, syms in per_file.items():
        for _, n in syms:
            cls_files[classname(n)].add(f)

    # machine-readable function -> original file (consumed by ApplyInventory.java for plate comments)
    ff = os.path.join(ROOT, "reference", "coverage", "funcfile.tsv")
    rows = ["symbol\tfile"]
    for f, syms in sorted(per_file.items()):
        for _, n in sorted(syms):
            rows.append(f"{n}\t{f}")
    open(ff, "w").write("\n".join(rows) + "\n")

    if len(sys.argv) > 1:
        want = sys.argv[1]
        for f, syms in sorted(per_file.items()):
            ms = [(a, n) for a, n in syms if classname(n) == want]
            if ms:
                print(f"# {want}  ->  {f}")
                for a, n in sorted(ms):
                    print(f"  {a:08x} {n}")
        return

    ts = sorted(f for f in per_file if f.startswith("TS_"))
    L = ["# Original source-file map (recovered from ts_i386.so STT_FILE markers)", "",
         "Every function's ORIGINAL `.cpp`, via the per-TU `gcc2_compiled.` address ranges. "
         "Generated by `scripts/coverage/filemap.py`. The reconstruction matches methods by name "
         "(`reconstruction.py`); pair this with that to diff our layout + names vs the reference.", "",
         "## TS_*.cpp files (the mod's own TUs) — classes per file", "",
         "| original file | classes (method count) |", "|---|---|"]
    for f in ts:
        by_cls = defaultdict(int)
        for _, n in per_file[f]:
            by_cls[classname(n)] += 1
        cells = ", ".join(f"{c} ({k})" for c, k in sorted(by_cls.items(), key=lambda x: -x[1]))
        L.append(f"| `{f}` | {cells} |")

    L += ["", "## Class -> original file index (TS classes)", "",
          "| class | original file(s) |", "|---|---|"]
    for c in sorted(cls_files):
        if c in ("(free)",):
            continue
        files = sorted(cls_files[c])
        if not any(x.startswith("TS_") for x in files):
            continue
        flag = "  ⚠️SPLIT" if len(files) > 1 else ""
        L.append(f"| `{c}` | {', '.join(f'`{x}`' for x in files)}{flag} |")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as fh:
        fh.write("\n".join(L) + "\n")
    print(f"wrote {OUT}: {len(ts)} TS files, {sum(1 for c in cls_files if c!='(free)')} classes")


if __name__ == "__main__":
    main()
