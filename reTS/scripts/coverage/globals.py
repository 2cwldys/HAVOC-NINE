#!/usr/bin/env python3
"""
globals.py — recover GLOBAL + STATIC-MEMBER variables (name + address + size + section) from ts_i386.so.

Two kinds of data symbol:
  - static class members  : `_<len><Class>.<member>`  -> attributed to the class (e.g. CTSBriefcase.s_nextFlagID)
  - free globals          : plain names (TSGameRules, gmsg*, g_*, …)
Sizes come from `nm -S`; section (D/B/R) tells data vs bss vs rodata. This is the global half of the
Phase-1 variable inventory (members.py does the per-object members). TS-relevant symbols are surfaced;
stock-SDK globals are counted but collapsed (use the baseline class set to tag class statics).

Outputs:
  reference/coverage/GLOBALS.md     — human report (TS class statics + TS free globals)
  reference/coverage/globals.tsv    — machine: scope<TAB>name<TAB>addr<TAB>size<TAB>section

  python3 scripts/coverage/globals.py
"""
import os, re, subprocess
from collections import defaultdict

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SO   = os.path.join(ROOT, "reference", "ts_i386.so")
WORK = os.path.join(ROOT, "reference", "coverage", "ts_specific.txt")
OUT_MD  = os.path.join(ROOT, "reference", "coverage", "GLOBALS.md")
OUT_TSV = os.path.join(ROOT, "reference", "coverage", "globals.tsv")

SECT = {"D": ".data", "d": ".data", "B": ".bss", "b": ".bss", "R": ".rodata", "r": ".rodata",
        "G": ".sdata", "g": ".sdata", "S": ".sbss", "s": ".sbss"}
# free globals that are clearly TS / mod-level (vs stock SDK engine globals)
TS_GLOBAL = re.compile(r"(TS|^gmsg|^g_ts|^g_TS|RoundTime|SlowMot|^sv_ts|Specialist)", re.I)


def ts_classes():
    s = set()
    if os.path.exists(WORK):
        for ln in open(WORK):
            if "::" in ln:
                s.add(ln.split("::", 1)[0])
    return s


def main():
    tscls = ts_classes()
    nm = subprocess.run(f"nm -S '{SO}'", shell=True, capture_output=True, text=True).stdout
    statics = defaultdict(list)   # class -> [(member, addr, size, sect)]
    ts_free, other_free = [], 0
    for ln in nm.splitlines():
        p = ln.split()
        if len(p) < 4:
            continue
        addr, size, typ, name = p[0], p[1], p[2], p[3]
        if typ not in SECT:
            continue
        sect = SECT[typ]
        m = re.match(r"^_(\d+)([A-Za-z_]\w*)\.(\w+)$", name)
        if m:
            cls, mem = m.group(2)[: int(m.group(1))], m.group(3)
            if re.search(r"[Ss]ave\w*$", mem):   # the save tables themselves — members.py parses them
                continue
            statics[cls].append((mem, int(addr, 16), int(size, 16), sect))
        elif "." not in name and "__" not in name:   # a plain free global (skip mangled fn-statics)
            if TS_GLOBAL.search(name):
                ts_free.append((name, int(addr, 16), int(size, 16), sect))
            else:
                other_free += 1

    ts_statics = {c: v for c, v in statics.items() if c in tscls}
    other_static_cls = len(statics) - len(ts_statics)

    L = ["# Recovered global + static-member variables (ts_i386.so)", "",
         "Generated by `scripts/coverage/globals.py`. The global half of the variable inventory "
         "(per-object members are in `members.py`). Addresses/sizes from `nm -S`; offsets are provenance.", "",
         f"**TS class statics: {sum(len(v) for v in ts_statics.values())} across {len(ts_statics)} classes · "
         f"TS free globals: {len(ts_free)} · (stock: {other_static_cls} classes' statics + {other_free} free globals omitted).**",
         "", "## TS class static members", "", "| class | member | size | section |", "|---|---|--:|---|"]
    tsv = ["scope\tname\taddr\tsize\tsection"]
    for c in sorted(ts_statics):
        for mem, addr, size, sect in sorted(ts_statics[c], key=lambda x: x[1]):
            L.append(f"| `{c}` | `{mem}` | {size} | {sect} |")
            tsv.append(f"{c}\t{c}.{mem}\t0x{addr:x}\t{size}\t{sect}")

    L += ["", "## TS free globals", "", "| name | size | section |", "|---|--:|---|"]
    for name, addr, size, sect in sorted(ts_free):
        L.append(f"| `{name}` | {size} | {sect} |")
        tsv.append(f"global\t{name}\t0x{addr:x}\t{size}\t{sect}")

    open(OUT_MD, "w").write("\n".join(L) + "\n")
    open(OUT_TSV, "w").write("\n".join(tsv) + "\n")
    print(f"wrote {OUT_MD} + {OUT_TSV}: {sum(len(v) for v in ts_statics.values())} TS statics "
          f"({len(ts_statics)} classes), {len(ts_free)} TS free globals")


if __name__ == "__main__":
    main()
