// tsm_spawns for h9_tsrp_hive: one team starts in Paradise City, the other in Xenon City.
//
// ts_matchmode ignores a map's info_player_deathmatch entities once a per-map cfg exists, so the merged
// map needs its own list. Every point here is proved with the kit's space model: floor under the feet,
// level under the whole body and on the home point's own floor, a standing body's clearance, dry footing,
// a straight walk to it from the home point or another start, clear of the brush entities a body must not
// start in or on, 96 from the next start, and no point near a travel zone (a start must not throw a
// player straight to another city). Alexandria stays neutral: no team starts there, and both teams reach it
// through the travel zones. tools\spawns64.py checks the result against the compiled map.
//
//   node spawns.mjs            write out/tsm_spawns_h9_tsrp_hive.cfg
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { M } from "../lib.mjs";
import { floorBelow, footing } from "./spots.mjs";

const MAP = join(process.cwd(), "out", "h9_tsrp_hive.map");
const OUT = join(process.cwd(), "out", "tsm_spawns_h9_tsrp_hive.cfg");
const WANT = 32; // one team's whole spawn set, all in its home city: a side at 64 players
const PAD_CLEAR = 84; // pad half-diagonal (34) + player half-width (16) + margin
const SPREAD = 96; // between two starts, so a full team does not pile on one tile
const FEET = 36;
// brush entities a body must not start in: doors and walls in the city's own walls, breakables, lifts, ladders,
// and the water and the hurt the space model does not count
const KEEP_OUT = new Set(["func_wall", "func_door", "func_door_rotating", "func_breakable", "func_train", "func_plat",
  "func_rotating", "func_pushable", "func_button", "func_tracktrain", "func_conveyor", "func_rot_button",
  "func_guntarget", "momentary_door", "func_ladder", "func_water", "trigger_hurt"]);
const STEP = 16; // how finely the walk to a start is tried
const WALK = 384; // the longest straight walk tried to a start

const map = M.readMap(readFileSync(MAP, "utf8"));
const space = M.spaceOf(map);

const valueOf = (value) => String(value ?? "").trim().split(/\s+/).map(Number);

function boundsOf(brush) {
  const shape = M.shapeOf(brush);
  const min = [Infinity, Infinity, Infinity];
  const max = [-Infinity, -Infinity, -Infinity];
  for (const face of shape.faces) for (const point of face.polygon)
    for (let a = 0; a < 3; a++) {
      min[a] = Math.min(min[a], point[a]);
      max[a] = Math.max(max[a], point[a]);
    }
  return Number.isFinite(min[0]) ? { min, max } : null;
}

/*
 * WHERE EACH TEAM STARTS: a ring round `at` (a player origin, 36 over the floor) facing `yaw`, kept PAD_CLEAR
 * from every travel zone in its city and from `keepOut` -- the spot each ring has always been kept clear of,
 * so the starts are the set the deployed cfg and its players already know.
 */
const homes = [
  { team: 1, prefix: "pc", name: "Paradise City", at: [-468, 1895, -270], yaw: 0, keepOut: [[-384, 1896]] },
  { team: 2, prefix: "xe", name: "Xenon City", at: [-39, 152, 1015], yaw: 0, keepOut: [[40, 152]] },
];

const centreOf = (entity) => {
  const boxes = (entity.brushes ?? []).map(boundsOf).filter(Boolean);
  const min = [0, 1].map((a) => Math.min(...boxes.map((b) => b.min[a])));
  const max = [0, 1].map((a) => Math.max(...boxes.map((b) => b.max[a])));
  return { x: (min[0] + max[0]) / 2, y: (min[1] + max[1]) / 2 };
};
const everyTeleport = map.entities.filter((e) => e.classname === "trigger_teleport").map(centreOf);
const keptOut = map.entities.filter((e) => KEEP_OUT.has(e.classname)).flatMap((e) => (e.brushes ?? []).map(boundsOf)).filter(Boolean);
/** Whether a body standing on `floor` at x y, 8 units of play round it, touches one of those entities or stands
 *  on one (a breakable or a moving floor is not the world's). */
const inEntity = (x, y, floor) =>
  keptOut.some((b) => x + 24 > b.min[0] && x - 24 < b.max[0] && y + 24 > b.min[1] && y - 24 < b.max[1] && floor + 72 > b.min[2] && floor - 4 < b.max[2]);
/** Whether the floor is level under a body's whole footprint: no stair, curb or ledge under any corner. */
const level = (x, y, floor) =>
  [[-14, -14], [14, -14], [-14, 14], [14, 14]].every(([dx, dy]) => {
    const under = floorBelow(space, x + dx, y + dy, floor + 8, 24);
    return under !== null && Math.abs(under - floor) <= 1;
  });

const lines = [
  "// ts_matchmode spawn points for h9_tsrp_hive -- generated by spawns.mjs from the merged map",
  "// tsm_spawn <team> <x> <y> <z> <pitch> <yaw> <tier>",
];
let total = 0;
const report = [];

for (const { team, prefix, name, at: anchorAt, yaw, keepOut } of homes) {
  const pads = [
    ...keepOut.map(([x, y]) => ({ x, y })),
    ...map.entities.filter((e) => e.classname === "trigger_teleport" && String(e.targetname ?? "").startsWith(`hive_${prefix}_pad_`)).map(centreOf),
  ];

  const floor = floorBelow(space, anchorAt[0], anchorAt[1], anchorAt[2], 64);
  if (floor === null) throw new Error(`${prefix}: no floor under the home point`);
  const anchor = footing(space, anchorAt[0], anchorAt[1], floor, { slack: 1 });
  if (!anchor) throw new Error(`${prefix}: the home point has no standing room`);

  const chosen = [];
  const fits = (x, y) => {
    if (pads.some((pad) => Math.hypot(pad.x - x, pad.y - y) < PAD_CLEAR)) return false;
    return !chosen.some((spot) => Math.hypot(spot.x - x, spot.y - y) < SPREAD);
  };
  // a start stands on the home point's own floor, level, and a body walks to it in a straight line from the
  // home point or from a start already chosen, no more than WALK away: the same square or hall, never a
  // ledge, a stair or the room behind a wall
  const line = (from, x, y) => {
    const steps = Math.ceil(Math.hypot(x - from.x, y - from.y) / STEP);
    for (let k = 1; k < steps; k++) {
      const t = k / steps;
      if (!footing(space, from.x + (x - from.x) * t, from.y + (y - from.y) * t, anchor.floor, { slack: 1 })) return false;
    }
    return true;
  };
  const walked = (x, y) => [anchor, ...chosen].some((from) => Math.hypot(x - from.x, y - from.y) <= WALK && line(from, x, y));
  const add = (x, y, atFloor) => {
    if (!fits(x, y)) return false;
    const spot = footing(space, x, y, atFloor, { slack: 1 });
    if (!spot || Math.abs(spot.floor - anchor.floor) > 1 || inEntity(x, y, spot.floor) || !level(x, y, spot.floor) || !walked(x, y)) return false;
    chosen.push({ ...spot, angle: yaw });
    return true;
  };

  add(anchor.x, anchor.y, anchor.floor);
  // rings out from the home point, 24 apart, each tried at 32 bearings
  for (let radius = 48; radius <= 768; radius += 24) {
    if (chosen.length >= WANT) break;
    for (let i = 0; i < 32 && chosen.length < WANT; i++) {
      const angle = (i / 32) * Math.PI * 2;
      const x = Math.round(anchor.x + Math.cos(angle) * radius);
      const y = Math.round(anchor.y + Math.sin(angle) * radius);
      const under = floorBelow(space, x, y, anchor.floor + 32, 64);
      if (under === null) continue;
      add(x, y, under);
    }
  }
  if (chosen.length < WANT) throw new Error(`${prefix}: only ${chosen.length} safe starts around the home point, wanted ${WANT}`);
  const tooNear = chosen.find((spot) => everyTeleport.some((zone) => Math.hypot(zone.x - spot.x, zone.y - spot.y) < PAD_CLEAR));
  if (tooNear) throw new Error(`${prefix}: the start at ${tooNear.x} ${tooNear.y} is within ${PAD_CLEAR} of a travel zone`);
  lines.push(`// team ${team}: ${name}`);
  for (const spot of chosen) {
    lines.push(`tsm_spawn ${team} ${spot.x} ${spot.y} ${(spot.floor + FEET).toFixed(2)} 0 ${spot.angle} 0`);
    total++;
  }
  report.push(`team ${team}  ${prefix} ${name.padEnd(14)} ${chosen.length} starts around (${anchor.x}, ${anchor.y}, ${anchor.floor})`);
}

writeFileSync(OUT, lines.join("\r\n") + "\r\n");
console.log(`wrote ${OUT}`);
for (const line of report) console.log(`  ${line}`);
console.log(`  ${total} tsm_spawn lines, ${lines.length} lines total`);
